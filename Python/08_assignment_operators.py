# Assignment Operators

a = 2   # ''=' is an assignment operator that assigns the value 2 to the variable a.


# Compound Assignment Operators

b = 20
b += 40
b += 60
print("The value of b after compound assignment is: ", b)  # Print the value of b after compound assignment.


c = 100
c -= 20
c -= 30
print("The value of c after compound assignment is: ", c)  # Print the value of c after compound assignment.


d = 3
d *= 2
d *= 1
print("The value of d after compound assignment is: ", d)  # Print the value of d after compound assignment.


e = 50
e /= 2
e /= 5
print("The value of e after compound assignment is: ", e)  # Print the value of e after compound assignment.


f = 60
f //= 5
f //= 3
f //= 2
print("The value of f after compound assignment is: ", f)  # Print the value of f after compound assignment.