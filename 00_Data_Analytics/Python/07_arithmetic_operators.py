# Arithmetic Operators

a = int(input("Enter a number: "))  # Taking input from user as int.
b = int(input("Enter another number: "))
print("Addition of the two numbers is: ", a + b)    # Print addition of two numbers.
print("Subtraction of the two numbers is: ", a - b)  # Print subtraction of two numbers.
print("Multiplication of the two numbers is: ", a * b)  # Print multiplication of two numbers.
print("Division of the two numbers is: ", a / b)  # Returns division in float.
print("Floor division of the two numbers is: ", a // b)  # Returns division in int.
print("Remainder of the two numbers is: ", a % b)  # Print remainder of two numbers.
print("Exponentiation of the two numbers is: ", a ** b)  # Print exponentiation of two numbers. Basically a raised to the power of b.

