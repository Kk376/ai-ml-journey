# Variables are used to store data in a program.
# You can think of a variable as a container that holds a value. 
# You can create a variable by assigning a value to it using the equals sign (=).

name = "Kushagra Kumar"  # This is a string variable that holds the name of the user.
age = 25  # This is an integer variable that holds the age of the user.
height = 6.4  # This is a float variable that holds the height of the user.

# Pascal case is a naming convention in which the first letter of each word in a variable name is capitalized.
# Example: FirstName, LastName, Age, Height

# Camel case is a naming convention in which the first letter of the first word is lowercase and the first letter of each subsequent word is capitalized.
# Example: firstName, lastName, age, height

# Snake case is a naming convention in which all letters are lowercase and words are separated by underscores.
# Example: first_name, last_name, age, height