# Input-Output

name = input("What's your name? \n")  # This will ask the user for their name and store it in the variable 'name'. 
age = int(input("What's your age? \n"))  # This will ask the user for their age and store it in the variable 'age'.

# Format the string using f-string formatting to include the name and age variables.
print(f"My name is {name} and I am {age} years old.")   # f before "" indicates that we are using f-string formatting. 
# The variables inside the curly braces {} will be replaced with their values when the string is printed. In this case, the value of the variable 'name' will be replaced with "Kushagra Kumar" and the value of the variable 'age' will be replaced with 25 when the string is printed.