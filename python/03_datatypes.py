# Numbers from -infinity to infinity are represented by the int data type in Python.
# Example; -2, 0, 2

a = 5   # This is an integer variable that holds the value 5.
print(a)  # This will print the value of the variable 'a'.
print(type(a), "\n")  # This will print the data type of the variable 'a', which is 'int'.

# The float data type is used to represent decimal numbers in Python.
# Example; -2.5, 0.0, 2.5

b = 5.0  # This is a float variable that holds the value 5.0.
print(b)  # This will print the value of the variable 'b'.
print(type(b), "\n")  # This will print the data type of the variable 'b', which is 'float'.

# The complex data type is used to represent complex numbers in Python.
# Example; 2 + 3j, 4 - 5j

c = 5j  # This is a complex variable that holds the value 5j. We can only use 'j' to represent the imaginary part of a complex number in Python.
print(c)  # This will print the value of the variable 'c'.
print(type(c), "\n")  # This will print the data type of the variable 'c', which is 'complex'.

# The string data type is used to represent text in Python. We use str to represent string data type in Python.
# Example; "Hello", 'World'

d = "Hello, Kushagra!"  # This is a string variable that holds the value "Hello, Kushagra!".
print(d)  # This will print the value of the variable 'd'.
print(type(d), "\n")  # This will print the data type of the variable 'd', which is 'str'.

# The boolean data type is used to represent truth values in Python. We use bool to represent boolean data type in Python.
# Example; True, False

e = True  # This is a boolean variable that holds the value True.
print(e)  # This will print the value of the variable 'e'.
print(type(e), "\n")  # This will print the data type of the variable 'e', which is 'bool'.

f = False  # This is a boolean variable that holds the value False.
print(f)  # This will print the value of the variable 'f'.
print(type(f), "\n")  # This will print the data type of the variable 'f', which is 'bool'.